#!/usr/bin/env python3
"""Summarize the Zenodo version history of both volumes as a markdown table.

Usage:
    python3 -I scripts/zenodo_history.py DIR > notes/zenodo-history.md

DIR holds the JSON pages fetched by `make zenodo` (files c<conceptid>_p<page>.json from
https://zenodo.org/api/records?q=conceptrecid:<id>&all_versions=true&size=25&page=<n>).
"""
import json
import sys
from datetime import date
from pathlib import Path

CONCEPTS = {
    "17957561": "Volume I (Foundations of Reason) concept record",
    "22975036": "Volume II (Engineering of Reason) concept record",
}


def main(argv):
    if len(argv) != 1:
        print(__doc__)
        return 2
    folder = Path(argv[0])
    print("# Zenodo publication history\n")
    print(f"Generated by `scripts/zenodo_history.py` from the Zenodo REST API on {date.today().isoformat()}.")
    print("Each row is one record under the concept DOI. Records include language editions and")
    print("spin-off documents, so the record count is larger than the number of numbered versions.")
    print("Rows are ordered by the date Zenodo created the record; the publication date is the one")
    print("the uploader entered, and the two disagree for record 18208467 (labelled v1.4r).\n")
    for concept, label in CONCEPTS.items():
        hits = []
        for page in sorted(folder.glob(f"c{concept}_p*.json")):
            hits += json.loads(page.read_text(encoding="utf-8"))["hits"]["hits"]
        hits.sort(key=lambda h: (h.get("created", ""), h["id"]))
        print(f"## {label} {concept}: {len(hits)} records\n")
        print("| Created | Published | Version field | Title | Record | License |")
        print("|---|---|---|---|---|---|")
        for hit in hits:
            meta = hit["metadata"]
            title = meta.get("title", "").replace("|", "/").strip()
            license_id = (meta.get("license") or {}).get("id", "")
            version = str(meta.get("version") or "").replace("|", "/")
            print(f"| {hit.get('created', '')[:10]} | {meta.get('publication_date')} | {version} | {title} | "
                  f"[{hit['id']}](https://zenodo.org/records/{hit['id']}) | {license_id} |")
        print()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
